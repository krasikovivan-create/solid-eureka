def welcome_back(agent_name: str, company: str) -> str:
    name = esc(agent_name) or "ваш виртуальный сотрудник"
    return (
        f"👋 Это {name}, на связи! {('Работаем на ' + esc(company) + '. ') if company else ''}"
        "Пишите задачу обычным языком или выберите раздел в меню."
    )


def onboarding_done(agent_name: str, agent_role: str, morning: str, evening: str) -> str:
    return (
        f"🎉 Готово! Я — {esc(agent_name)}, {esc(agent_role)}.\n\n"
        f"Каждое утро в {morning} пришлю план дня, а в {evening} — итоги "
        "(время можно поменять в /settings).\n\n"
        "Попробуйте написать: «Напомни завтра в 10 позвонить Иванову» "
        "или «Добавь клиента ООО Ромашка»."
    )


def access_denied(user_id: int) -> str:
    return (
        "⛔ У вас нет доступа к этому боту.\n"
        f"Ваш Telegram ID: <code>{user_id}</code>\n"
        "Попросите владельца добавить его в переменную ALLOWED_USER_IDS."
    )
